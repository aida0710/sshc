#!/usr/bin/env python3
"""Write the properties the terminal finds grapheme cluster boundaries with, from the Unicode data files.

Python's unicodedata has none of them (Grapheme_Cluster_Break, Extended_Pictographic,
Indic_Conjunct_Break), so the files are read from unicode.org at UNICODE_VERSION, the
version the width table is made from (generate-terminal-widths.py):

    python3 scripts/unicode/generate-grapheme-breaks.py

It also writes Unicode's boundary tests without their comments, for graphemeBreaks.test.ts.
"""
from pathlib import Path
import re
import urllib.request

UNICODE_VERSION = "17.0.0"
SOURCE = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd"
ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "web/src/terminal/graphemeBreakTable.generated.ts"
TEST_OUTPUT = ROOT / "web/src/terminal/testdata/grapheme-break-test.txt"
NOTICE = f"Unicode {UNICODE_VERSION}, © Unicode, Inc. (https://www.unicode.org/terms_of_use.html)."

# The class of a code point is these three properties in one number. The order and
# the bit positions are the ones graphemeBreaks.ts reads.
BREAK_CLASSES = [
    "Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
    "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT",
]
EXTENDED_PICTOGRAPHIC = 1 << 4
CONJUNCT_CLASSES = {"Consonant": 1 << 5, "Linker": 2 << 5, "Extend": 3 << 5}

LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)(?:\s*;\s*([A-Za-z_]+))?")


def fetch(path: str) -> str:
    with urllib.request.urlopen(f"{SOURCE}/{path}") as response:
        return response.read().decode("utf-8")


def entries(text: str):
    for line in text.splitlines():
        found = LINE.match(line)
        if found:
            first = int(found.group(1), 16)
            last = int(found.group(2) or found.group(1), 16)
            yield first, last, found.group(3), found.group(4)


def classes() -> dict[int, int]:
    found: dict[int, int] = {}
    for first, last, value, _ in entries(fetch("auxiliary/GraphemeBreakProperty.txt")):
        for codepoint in range(first, last + 1):
            found[codepoint] = BREAK_CLASSES.index(value)
    for first, last, value, _ in entries(fetch("emoji/emoji-data.txt")):
        if value == "Extended_Pictographic":
            for codepoint in range(first, last + 1):
                found[codepoint] = found.get(codepoint, 0) | EXTENDED_PICTOGRAPHIC
    for first, last, value, conjunct in entries(fetch("DerivedCoreProperties.txt")):
        if value == "InCB":
            for codepoint in range(first, last + 1):
                found[codepoint] = found.get(codepoint, 0) | CONJUNCT_CLASSES[conjunct]
    return found


def ranges(found: dict[int, int]) -> list[tuple[int, int, int]]:
    merged: list[tuple[int, int, int]] = []
    for codepoint in sorted(found):
        value = found[codepoint]
        if value == 0:
            continue
        if merged and merged[-1][1] == codepoint - 1 and merged[-1][2] == value:
            merged[-1] = (merged[-1][0], codepoint, value)
        else:
            merged.append((codepoint, codepoint, value))
    return merged


def table(merged: list[tuple[int, int, int]]) -> str:
    values = [f"0x{first:X}, 0x{last:X}, {value}" for first, last, value in merged]
    lines = [", ".join(values[index:index + 5]) for index in range(0, len(values), 5)]
    body = "\n".join(f"  {line}," for line in lines)
    return (
        "// Generated by scripts/unicode/generate-grapheme-breaks.py. Do not edit.\n"
        f"// {NOTICE}\n"
        "// Inclusive [first, last, class] triples; a code point in none of them has class 0.\n"
        "// A class is Grapheme_Cluster_Break in bits 0-3 (the order in the script),\n"
        "// Extended_Pictographic in bit 4, and Indic_Conjunct_Break in bits 5-6\n"
        "// (1 Consonant, 2 Linker, 3 Extend).\n\n"
        "export const graphemeBreakRanges: readonly number[] = [\n"
        f"{body}\n"
        "];\n"
    )


def boundary_tests() -> str:
    cases = []
    for line in fetch("auxiliary/GraphemeBreakTest.txt").splitlines():
        case = line.split("#", 1)[0].strip()
        if case:
            cases.append(case)
    header = f"# GraphemeBreakTest.txt of {NOTICE}\n# ÷ marks a boundary and × none; comments left out.\n"
    return header + "\n".join(cases) + "\n"


def main() -> None:
    OUTPUT.write_text(table(ranges(classes())), encoding="utf-8")
    TEST_OUTPUT.parent.mkdir(exist_ok=True)
    TEST_OUTPUT.write_text(boundary_tests(), encoding="utf-8")


if __name__ == "__main__":
    main()
