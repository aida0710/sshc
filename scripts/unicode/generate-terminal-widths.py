#!/usr/bin/env python3
"""Write the cell widths the terminal counts characters with, from Python's Unicode data.

The widths follow wcwidth (glibc, and string-width in Node): two cells for East
Asian Wide and Fullwidth characters, none for combining marks and format
characters, one for the rest. Run it with a Python whose unicodedata is
UNICODE_VERSION, so that the table does not change with the machine:

    python3 scripts/unicode/generate-terminal-widths.py
"""
from pathlib import Path
import unicodedata

UNICODE_VERSION = "17.0.0"
ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "web/src/terminal/unicodeWidthTable.generated.ts"

# Hangul medial vowels and final consonants join the leading consonant before them.
CONJOINING_JAMO = [(0x1160, 0x11FF), (0xD7B0, 0xD7FF)]


def width(codepoint: int) -> int:
    character = chr(codepoint)
    if codepoint == 0x00AD:  # SOFT HYPHEN is shown where a line breaks at it.
        return 1
    if codepoint == 0x200B or any(start <= codepoint <= end for start, end in CONJOINING_JAMO):
        return 0
    if unicodedata.category(character) in ("Mn", "Me", "Cf"):
        return 0
    if unicodedata.east_asian_width(character) in ("W", "F"):
        return 2
    return 1


def ranges(wanted: int) -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    # C0 and C1 controls are not characters to the table; the provider handles them.
    for codepoint in range(0xA0, 0x110000):
        if 0xD800 <= codepoint <= 0xDFFF or width(codepoint) != wanted:
            continue
        if found and found[-1][1] == codepoint - 1:
            found[-1] = (found[-1][0], codepoint)
        else:
            found.append((codepoint, codepoint))
    return found


def flattened(name: str, found: list[tuple[int, int]]) -> str:
    values = [f"0x{value:X}" for pair in found for value in pair]
    lines = [", ".join(values[index:index + 10]) for index in range(0, len(values), 10)]
    body = ",\n  ".join(lines)
    return f"export const {name}: readonly number[] = [\n  {body},\n];\n"


def main() -> None:
    if unicodedata.unidata_version != UNICODE_VERSION:
        raise SystemExit(f"unicodedata is {unicodedata.unidata_version}, not {UNICODE_VERSION}")
    major = UNICODE_VERSION.split(".")[0]
    OUTPUT.write_text(
        "// Generated by scripts/unicode/generate-terminal-widths.py. Do not edit.\n"
        f"// Unicode {UNICODE_VERSION}. Each array holds inclusive [first, last] code point pairs.\n\n"
        f'export const unicodeVersion = "{major}";\n\n'
        + flattened("zeroWidthRanges", ranges(0))
        + "\n"
        + flattened("wideRanges", ranges(2)),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
