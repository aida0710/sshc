#!/usr/bin/env python3
"""Write the ssh_config keywords OpenSSH accepts, from openssh-portable's readconf.c.

OpenSSH stops reading the whole configuration at a keyword that is not in the
keywords[] table of readconf.c ("Bad configuration option"). Every name in the
table is accepted, including the ones ssh reads past as deprecated, unsupported
or ignored, so the list keeps every name and drops the opcodes.

The source is downloaded and only read as text. To follow a new release, change
OPENSSH_TAG and run:

    python3 -I scripts/openssh/generate-config-keywords.py
"""
from pathlib import Path
import re
import urllib.request

OPENSSH_TAG = "V_10_2_P1"
SOURCE_URL = f"https://raw.githubusercontent.com/openssh/openssh-portable/{OPENSSH_TAG}/readconf.c"
# Where a reader of the generated file can see the same table.
BROWSE_URL = f"https://github.com/openssh/openssh-portable/blob/{OPENSSH_TAG}/readconf.c"
ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "internal/config/openssh_keywords.gen.go"

TABLE = re.compile(r"\}\s*keywords\[\]\s*=\s*\{(?P<body>.*?)\{\s*NULL\s*,\s*oBadOption\s*\}", re.DOTALL)
ENTRY = re.compile(r'\{\s*"(?P<name>[^"]+)"\s*,\s*(?P<opcode>o[A-Za-z0-9]+)\s*\}')
# A table that lost one of these was not read right; ssh cannot work without them.
REQUIRED = {"host", "match", "include", "ignoreunknown", "hostname"}


def keywords(source: str) -> list[str]:
    table = TABLE.search(source)
    if table is None:
        raise SystemExit("readconf.c has no keywords[] table ending in { NULL, oBadOption }")
    names = {entry["name"] for entry in ENTRY.finditer(table["body"])}
    missing = REQUIRED - names
    if missing:
        raise SystemExit(f"the keywords[] table lacks {sorted(missing)}")
    for name in names:
        if not re.fullmatch(r"[a-z0-9]+", name):
            raise SystemExit(f"unexpected keyword {name!r}: OpenSSH compares lower-case names")
    return sorted(names)


def main() -> None:
    with urllib.request.urlopen(SOURCE_URL, timeout=30) as response:
        source = response.read().decode("utf-8")
    entries = "".join(f'\t"{name}",\n' for name in keywords(source))
    OUTPUT.write_text(
        "// Code generated by scripts/openssh/generate-config-keywords.py; DO NOT EDIT.\n\n"
        "package config\n\n"
        f"// openSSHKeywordNames は、openssh-portable {OPENSSH_TAG} の readconf.c の keywords[] にある\n"
        "// 名前を並べたものである。廃止・未対応として読み飛ばすもの（oDeprecated・oUnsupported・\n"
        "// oIgnore）も入る。OpenSSH が止まるのは、この表に無い名前だけだからである。\n"
        f"// {BROWSE_URL}\n"
        "var openSSHKeywordNames = []string{\n"
        f"{entries}"
        "}\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
