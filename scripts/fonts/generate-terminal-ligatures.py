#!/usr/bin/env python3
"""Write the character sequences the bundled JetBrains Mono draws as one ligature.

The font names each ligature glyph after the characters it replaces
(hyphen_greater.liga is ->), so the list is read from the glyph names. It needs
fontTools with WOFF2 support:

    pip install fonttools brotli
    python3 scripts/fonts/generate-terminal-ligatures.py
"""
import json
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "web/public/fonts/JetBrainsMono-Regular.woff2"
OUTPUT = ROOT / "web/src/terminal/ligatureTable.generated.ts"
SUFFIX = ".liga"


def sequences() -> list[str]:
    font = TTFont(FONT)
    characters: dict[str, str] = {}
    for codepoint, name in font.getBestCmap().items():
        characters.setdefault(name, chr(codepoint))
    found = {
        "".join(characters[part] for part in name[: -len(SUFFIX)].split("_"))
        for name in font.getGlyphOrder()
        if name.endswith(SUFFIX)
    }
    return sorted(found, key=lambda sequence: (-len(sequence), sequence))


def main() -> None:
    values = [json.dumps(sequence) for sequence in sequences()]
    lines = [", ".join(values[index:index + 12]) for index in range(0, len(values), 12)]
    body = "\n".join(f"  {line}," for line in lines)
    OUTPUT.write_text(
        "// Generated by scripts/fonts/generate-terminal-ligatures.py. Do not edit.\n"
        "// The sequences JetBrains Mono (web/public/fonts) draws as one ligature, longest first.\n\n"
        "export const ligatureSequences: readonly string[] = [\n"
        f"{body}\n"
        "];\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
