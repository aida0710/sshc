// Package enginelock は、エンジンを起こす資格をひとつだけにする。
//
// **エンジンは 1 台でなければならない。** 2 台上がると、あとから handoff を
// 書いた方が勝ち、先に繋いだ画面は誰も見ていないエンジンを見続ける。見えない
// まま残るのは、生きた SSH 接続・PTY・転送したポート、そして解錠された vault
// である。
//
// **これを構造で塞ぐのは、状態を読んで決められないからである。** 「エンジンは
// 居るか」を尋ねてから起こすと、同時に起動した 2 つが両方「居ない」と読み、
// 両方が上がる。ロックは取れるか取れないかのどちらかで、その間に隙間が無い。
//
// OS のファイルロックを使うのは、**プロセスが死ねば必ず外れる**からである。
// O_EXCL で作ったファイルや PID を書いた目印は、強制終了された起動が置いて
// いったものと、いま握られているものを区別できない——前者は永久に誰も
// エンジンを起こせなくする。ここに polling も stale 判定も置かないのは、その
// 区別を自分で書いた瞬間に、区別を間違える道が生まれるからである。
package enginelock

import (
	"errors"
	"os"
	"sync"
)

// ErrRunning は、別のプロセスが既にこのロックを握っていることを言う。
//
// **これは失敗ではない。** 求めていた状態——エンジンが 1 台居る——が既に
// 成立しているという報せである。ロック衝突として実際に観測した結果だけが
// これになり、他のあらゆる失敗は元のまま返る。
var ErrRunning = errors.New("an sshc engine is already running")

// Acquire は、path のロックを待たずに取る。
//
// path は engine.lock の完全なパスである。親ディレクトリは、無ければ作られ、
// あっても所有者だけが触れる状態へ締め直される。
//
// 待たないのは、待つ意味が無いからである。既に 1 台居るなら、待って 2 台目に
// なるのではなく、居る方の入口を出して終わるのが答えである。
//
// 返る release は、ロックを外してファイルを閉じる。二度以上呼んでよく、
// 複数の goroutine から同時に呼んでもよい。どの呼び出しも同じ結果を返す。
// 取得に失敗したときは release を返さない——握っていないロックを解放した
// つもりにさせないためである。
func Acquire(path string) (func() error, error) {
	return acquire(path)
}

// newRelease は、解放を一度だけ行い、その結果を後続の呼び出しへ配る。
//
// Task 5 の終了経路では、同じ release が正常経路と失敗経路の両方に現れうる。
// 二度目が「既に閉じた」エラーを返せば、正常な終了が失敗として報告される。
func newRelease(file *os.File, unlock func() error) func() error {
	var once sync.Once
	var result error
	return func() error {
		once.Do(func() { result = errors.Join(unlock(), file.Close()) })
		return result
	}
}
