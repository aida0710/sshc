package platform

// Toolchain は、このマシンにインストールされた OpenSSH のプログラムを見つける。
//
// **残っているのは ssh-keygen だけである。** 接続も、agent への登録も、
// アルゴリズムの一覧も、このプロセスの中で行う。ssh-keygen が残るのは、
// ハードウェアトークンとのやり取り（PIN、タッチ、libfido2）が x/crypto に
// 無いからである。
//
// **見つけるだけで、起こさない。** かつてはこの隣に OutputRunner という継ぎ目が
// 並んでいて、見つけたプログラムを実行するのはそちらの仕事だった。外部の ssh を
// 退けたときに実行する相手が居なくなり、継ぎ目は本番のどこからも呼ばれないまま
// 残っていたので、消した。KeyGen が返すパスは画面に出す引数の並びに入り、
// 走らせるのは利用者である。
//
// このアプリケーションが名前を知ってよいプログラムはここに全部あるので、呼び出し側
// が自前でプログラムパスを組み立てることは決してできない。必要なものを要求し、
// 絶対パスかエラーを受け取る。
type Toolchain interface {
	KeyGen() (string, error)
}
