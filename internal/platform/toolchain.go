package platform

// Toolchain は、このマシンにインストールされた OpenSSH のプログラムを見つける。
//
// 残っているのは ssh-keygen だけである。接続も、agent への登録も、
// アルゴリズムの一覧も、このプロセスの中で行う。ssh-keygen が残るのは、
// ハードウェアトークンとのやり取り（PIN、タッチ、libfido2）が x/crypto に
// 無いからである。
//
// このインターフェースはプログラムを検索するだけで起動しない。KeyGen は、
// ハードウェア鍵の項目を出してよいか（このマシンに ssh-keygen があるか）を
// 判断するためだけに使い、返すパスは使わない。画面に表示するコマンドの
// ssh-keygen は、利用者のシェルが PATH で解決する。そのため、ここで見つけた
// 実行ファイルと、利用者が実行する ssh-keygen が同じとは限らない。
//
// このアプリケーションが存在を確かめるプログラムはここに全部ある。必要なものを
// 要求し、絶対パスかエラーを受け取る。
type Toolchain interface {
	KeyGen() (string, error)
}
