package terminal

// leftoverModeReset は、終わったプログラムが有効にしたままのターミナルのモードを戻す列である。
//
// 切断で終わったプログラムは、マウスの報告を止めるといった後始末の列を送れない。
// そのままだと再接続した新しいシェルに、マウスの動きが「35;12;40M」のような文字で届く。
// プロセスの世代が終わるたびにこの列を出力へ足す。出力の一部なので、あとからアタッチして
// はじめから再生したブラウザも、つながっていたブラウザと同じ状態になる。
//
// 画面の内容とスクロールバックは消さないので、全体のリセット（RIS）は使わない。
// xterm.jsでの効き方は web/src/terminal/leftoverModeReset.test.ts が
// testdata/leftover-mode-reset.json の同じ列で確かめる。
const leftoverModeReset = "" +
	// 代替画面を抜けて、スクロールバックのある通常の画面へ戻る。?1049lは抜けたあとに
	// 通常の画面で保存したカーソル位置へ戻す。すでに通常の画面にいるときに古い位置へ
	// 飛ばないよう、先にDECSC（ESC 7）で今の位置を保存する。保存先は画面ごとに別なので、
	// 代替画面にいたときは?1049hで保存した位置へ戻る。
	"\x1b7\x1b[?1049l" +
	// マウスの報告の方式と形式のすべて。
	"\x1b[?9;1000;1002;1003;1005;1006;1015;1016l" +
	// フォーカスの報告とbracketed paste。新しいシェルは要るなら自分で有効にし直す。
	"\x1b[?1004;2004l" +
	// 同期出力。DECSTRでも戻るが、DECRSTでないとxterm.jsが止めていた描画を再開しない。
	"\x1b[?2026l" +
	// kitty keyboard protocolのフラグを0にする。残るとシェルへCtrl+CがCSI uの形で届く。
	// 先に積まれた分より多くpopしてスタックを空にする。残すと、次のシェルでpushしていない
	// プログラムがpopしたときに、終わったプログラムのフラグへ戻る。99はスタックの上限
	// （web/src/terminal/kittyKeyboard.tsのKITTY_KEYBOARD_STATE_STACK_LIMIT、64）より大きい数である。
	"\x1b[<99u\x1b[=0;1u" +
	// DECSTR: 文字の属性、スクロール範囲、カーソルの表示、カーソルキーとキーパッドのモード。
	"\x1b[!p"
