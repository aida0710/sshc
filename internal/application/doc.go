// Package application は、~/.ssh の設定を読み書きするユースケースを保持する。
//
// 無損失な設定エンジン（internal/config・internal/effective）と、ファイルの
// トランザクションマネージャ（internal/storage）の間に立つ。syscall を直接
// 行うことは決してなく、すべての読み書きは与えられた storage workspace を経由する。
//
// **ここはアプリケーション全体のユースケース層ではない。** 名前からはそう読めるが、
// 実際に持っているのは設定と、それに付随するもの（グループ、metadata、鍵の再配置、
// 接続の作成と更新）である。保管庫と同期にまたがるユースケース——マスターパスワード
// の変更が local rekey と remote reseal を 1 つの順序として扱うところ——は、
// internal/httpserver の vaultOperations が持つ。**あれは HTTP のためのものではなく、
// ブラウザと CLI の両方が同じ 1 つを共有する順序境界である。**
//
// 層を揃えたければ、あの順序境界をここへ引き上げることになる。そうすると
// internal/remotesync への依存がこのパッケージに生まれるので、いまの形は
// 「設定のユースケースはここ、保管庫と同期のユースケースは境界の側」という
// 意図的な分担である。**読む人が探す場所を間違えないよう、書いておく。**
